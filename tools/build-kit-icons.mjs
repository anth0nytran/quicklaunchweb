// Regenerates lib/kitIconSvgs.ts from public/home/icons/*.svg so icons can be
// drawn inline (stroke draw-on animation). Run: node tools/build-kit-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "public/home/icons";
const out = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(join(dir, file), "utf8");
  const viewBox = (svg.match(/viewBox="([^"]+)"/) || [])[1] || "0 0 24 24";
  const inner = (svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/) || [])[1];
  if (!inner) continue;
  // pathLength="1" lets one CSS dash rule draw any shape, whatever its real length.
  const drawable = inner
    .replace(/<(path|rect|circle|line|polyline|polygon|ellipse)\b/g, '<$1 pathLength="1"')
    .replace(/\s+/g, " ")
    .trim();
  out[file.replace(/\.svg$/, "")] = { viewBox, inner: drawable };
}
const body = `// GENERATED by tools/build-kit-icons.mjs from public/home/icons. Do not edit by hand.
export const KIT_ICON_SVGS: Record<string, { viewBox: string; inner: string }> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("lib/kitIconSvgs.ts", body);
console.log(`wrote ${Object.keys(out).length} icons`);
